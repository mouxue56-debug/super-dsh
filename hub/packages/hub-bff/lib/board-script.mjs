// 镜像目录里的 ./board。纯 CommonJS，不依赖包装所在目录是不是模块。
// 令牌只通过 HUB_BOARD_CONFIG 交给 hub-handoff，不出现在命令行，脚本也不打印。

export function renderBoardScript(handoff) {
  const quoted = JSON.stringify(String(handoff));
  return [
    '#!/usr/bin/env node',
    '// 任务板回写包装：转调 hub-handoff。令牌只经配置文件，不进命令行，也不打印。',
    "const { spawn } = require('node:child_process');",
    "const { lstat } = require('node:fs/promises');",
    "const { dirname, join } = require('node:path');",
    'const handoff = ' + quoted + ';',
    'const nameOk = /^[A-Za-z0-9_.-]{1,64}$/u;',
    'const say = (text) => process.stderr.write(text + "\\n");',
    'async function main() {',
    '  const args = process.argv.slice(2);',
    "  let identity = process.env.BOARD_IDENTITY || '';",
    '  const forward = [];',
    '  let usedAs = false;',
    '  for (let i = 0; i < args.length; i += 1) {',
    "    if (!usedAs && args[i] === '--as' && args[i + 1] && !String(args[i + 1]).startsWith('--')) {",
    '      identity = args[i + 1];',
    '      usedAs = true;',
    '      i += 1;',
    '      continue;',
    '    }',
    '    forward.push(args[i]);',
    '  }',
    "  let config = process.env.HUB_BOARD_CONFIG || '';",
    '  if (!config) {',
    '    if (!identity || !nameOk.test(identity)) {',
    "      say('还不知道你是谁。请加 --as 身份名，或设置环境变量 BOARD_IDENTITY。');",
    '      process.exit(2);',
    '    }',
    "    const beside = join(dirname(process.argv[1]), '..', 'board-identity');",
    "    config = join(beside, identity + '.json');",
    '  }',
    '  let info;',
    '  try {',
    '    info = await lstat(config);',
    '  } catch {',
    '    const who = nameOk.test(identity) ? identity : "";',
    '    say(who',
    "      ? '找不到「' + who + '」的令牌配置。请让主人把 0600 的文件放在镜像目录旁边的 ' +",
    "        'board-identity/' + who + '.json（字段 url、token），或设置 HUB_BOARD_CONFIG。'",
    "      : '找不到令牌配置。请设置 HUB_BOARD_CONFIG，指向 0600 的文件（字段 url、token）。');",
    '    process.exit(2);',
    '  }',
    '  if (!info.isFile()) {',
    "    say('令牌配置不是普通文件，没有使用它。');",
    '    process.exit(2);',
    '  }',
    '  if ((info.mode & 0o7777) !== 0o600) {',
    "    say('令牌配置的权限不对。它必须只有本人能读写（0600）。没有打开里面的内容。');",
    '    process.exit(2);',
    '  }',
    '  const env = Object.assign({}, process.env, { HUB_BOARD_CONFIG: config });',
    '  delete env.HUB_BOARD_URL;',
    '  delete env.HUB_BOARD_TOKEN;',
    '  const child = spawn(process.execPath, [handoff].concat(forward), {',
    "    env: env, stdio: 'inherit'",
    '  });',
    "  child.on('error', () => {",
    "    say('没能启动看板命令。');",
    '    process.exit(1);',
    '  });',
    "  child.on('exit', (code, signal) => {",
    '    if (signal) {',
    '      process.kill(process.pid, signal);',
    '      return;',
    '    }',
    '    process.exit(code == null ? 1 : code);',
    '  });',
    '}',
    'main();',
    '',
  ].join('\n');
}
